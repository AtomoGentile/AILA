"""Import the school's two-page 2026/27 grid. Requires pdfplumber; no AI/API calls.
Usage: python scripts/import_class_timetable.py school.pdf
The output is reviewed source data, not a runtime PDF download.
"""
import hashlib
import json
from pathlib import Path
import re
import sys
import pdfplumber

SOURCE = 'https://cspace.spaggiari.eu/pub/TVII0007/Orario/as_2627/All%201%20-%20Orario%20Definitivo%20Classi%202026-27.pdf'
OUTPUT = Path(__file__).resolve().parents[1] / 'shared/src/commonMain/kotlin/circolareplus/data/SchoolTimetableData.kt'

def extract(path):
    result = {}
    with pdfplumber.open(path) as pdf:
        assert len(pdf.pages) == 2, 'Review importer before using a different document layout'
        for page in pdf.pages:
            ys = []
            for y in sorted(set(e['top'] for e in page.edges if e['orientation'] == 'h')):
                if not ys or y - ys[-1] > .5:
                    ys.append(y)
            assert len(ys) == 52
            headers = [w for w in page.extract_words() if re.fullmatch(r'[1-5][A-D](?:sc|sa|sp|cl)', w['text'])]
            assert len(headers) in (21, 23)
            for header in headers:
                center = (header['x0'] + header['x1']) / 2
                # Adjacent class columns are 34.637 PDF points wide.
                left, right = center - 17.2, center + 17.2
                days, row = [], 2
                for count in (8, 8, 8, 9, 8, 8):
                    lessons = []
                    for hour in range(count):
                        box = page.crop((left, ys[row] + .3, right, ys[row+1] - .1))
                        text = ' '.join((box.extract_text(x_tolerance=.4, y_tolerance=.5) or '').split())
                        if text and not set(text) <= {'*'}:
                            assert re.fullmatch(r"[A-ZÀ-Ü '\-]+", text), (header['text'], hour, text)
                            lessons.append(text)
                        else:
                            lessons.append('')
                        row += 1
                    while lessons and not lessons[-1]:
                        lessons.pop()
                    days.append(lessons)
                assert row == 51
                assert header['text'] not in result
                result[header['text'].upper()] = days
    assert len(result) == 44
    return result

if __name__ == '__main__':
    path = Path(sys.argv[1])
    data = extract(path)
    lines = ['package circolareplus.data', '', '// Generated by scripts/import_class_timetable.py; review against the original grid.',
             '// PDF SHA-256: ' + hashlib.sha256(path.read_bytes()).hexdigest(),
             'internal val SCHOOL_TIMETABLE_DATA: Map<String, List<List<String>>> = mapOf(']
    for key, days in sorted(data.items()):
        value = ', '.join('listOf(' + ', '.join(json.dumps(v, ensure_ascii=False) for v in day) + ')' if day else 'emptyList()' for day in days)
        lines.append(f'    "{key}" to listOf({value}),')
    lines.append(')')
    OUTPUT.write_text('\n'.join(lines) + '\n')
    print('Imported', len(data), 'classes; 4CSA:', data['4CSA'])
